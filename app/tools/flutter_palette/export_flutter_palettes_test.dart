import 'dart:convert';
import 'dart:io';

import 'package:c001apk_flutter/constants/constants.dart';
import 'package:crypto/crypto.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

// All 36 ColorScheme roles supported by this project's Compose Material 3 1.3.1.
// Use Flutter's real ColorScheme.fromSeed, not a port or an RGB approximation.
Map<String, Color> composeRoles(ColorScheme c) => {
  'primary': c.primary,
  'onPrimary': c.onPrimary,
  'primaryContainer': c.primaryContainer,
  'onPrimaryContainer': c.onPrimaryContainer,
  'inversePrimary': c.inversePrimary,
  'secondary': c.secondary,
  'onSecondary': c.onSecondary,
  'secondaryContainer': c.secondaryContainer,
  'onSecondaryContainer': c.onSecondaryContainer,
  'tertiary': c.tertiary,
  'onTertiary': c.onTertiary,
  'tertiaryContainer': c.tertiaryContainer,
  'onTertiaryContainer': c.onTertiaryContainer,
  // These deprecated Flutter roles remain public roles in Compose 1.3.1.
  // ignore: deprecated_member_use
  'background': c.background,
  // ignore: deprecated_member_use
  'onBackground': c.onBackground,
  'surface': c.surface,
  'onSurface': c.onSurface,
  // ignore: deprecated_member_use
  'surfaceVariant': c.surfaceVariant,
  'onSurfaceVariant': c.onSurfaceVariant,
  'surfaceTint': c.surfaceTint,
  'inverseSurface': c.inverseSurface,
  'inverseOnSurface': c.onInverseSurface,
  'error': c.error,
  'onError': c.onError,
  'errorContainer': c.errorContainer,
  'onErrorContainer': c.onErrorContainer,
  'outline': c.outline,
  'outlineVariant': c.outlineVariant,
  'scrim': c.scrim,
  'surfaceBright': c.surfaceBright,
  'surfaceDim': c.surfaceDim,
  'surfaceContainer': c.surfaceContainer,
  'surfaceContainerHigh': c.surfaceContainerHigh,
  'surfaceContainerHighest': c.surfaceContainerHighest,
  'surfaceContainerLow': c.surfaceContainerLow,
  'surfaceContainerLowest': c.surfaceContainerLowest,
};

String hex(Color c) =>
    c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase();

void main() {
  test('all native fixed colors exactly match pinned Flutter fromSeed', () {
    final nativeRoot = Platform.environment['NATIVE_ROOT'];
    expect(
      nativeRoot,
      isNotNull,
      reason: 'Set NATIVE_ROOT to the native checkout.',
    );
    final sdkRoot = Platform.environment['FLUTTER_ROOT'];
    expect(sdkRoot, isNotNull, reason: 'Set FLUTTER_ROOT to Flutter 3.47.7.');
    final version = jsonDecode(
      File('$sdkRoot/bin/cache/flutter.version.json').readAsStringSync(),
    ) as Map<String, dynamic>;
    expect(version['frameworkVersion'], '3.47.7');
    expect(
      version['frameworkRevision'],
      'abaf9c523780a608bd46686fd5e53740a07077f8',
    );
    final lock = File('pubspec.lock').readAsStringSync();
    final utilitiesLock = RegExp(
      r'^  material_color_utilities:\n((?: {4,}.*\n)+)',
      multiLine: true,
    ).firstMatch(lock)?.group(1);
    expect(utilitiesLock, isNotNull);
    expect(
      RegExp(
        r'^    version: "0\.13\.0"$',
        multiLine: true,
      ).hasMatch(utilitiesLock!),
      isTrue,
    );
    // Pin the actual call site as well as the seeds: a new variant, contrast
    // setting or theme customization requires deliberate review, never drift.
    const referenceFiles = {
      'lib/main.dart':
          '6df4e2ea7c462a83224aeaf18dd669342699ba30922cc47b84408d980a05ab4c',
      'lib/constants/constants.dart':
          'c63757ece40b46bcff66ad6535026953cf145d2d0bdd694acb8badc7dba280e4',
    };
    for (final reference in referenceFiles.entries) {
      expect(
        sha256.convert(File(reference.key).readAsBytesSync()).toString(),
        reference.value,
        reason:
            'Flutter theme source changed; manually review ${reference.key} before updating the pin.',
      );
    }
    final source = File(
      '$nativeRoot/app/src/main/java/io/github/ktclat/c001apk/nativeapp/settings/ThemePalette.kt',
    ).readAsStringSync();
    final nativeSeeds = RegExp(r'ThemeSeed\("[^"]+",\s*(0x[0-9A-Fa-f]+)\)')
        .allMatches(source)
        .map((match) => int.parse(match.group(1)!))
        .toList();
    expect(nativeSeeds, Constants.seedColors.map((c) => c.toARGB32()).toList());
    expect(nativeSeeds.length, 19);

    final kotlin = StringBuffer('''// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by app/tools/flutter_palette/export_flutter_palettes_test.dart.
// Flutter 3.47.7 (abaf9c523780a608bd46686fd5e53740a07077f8),
// material_color_utilities 0.13.0; tonalSpot, contrastLevel 0.0.
// Source seeds: c001apk Flutter constants.dart, stable stored indexes 0..18.
// Regenerate or verify via docs/FLUTTER_THEME_PARITY.md; do not hand-edit colors.
package io.github.ktclat.c001apk.nativeapp.settings

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
''');
    final fixture = StringBuffer(
      '# Flutter 3.47.7 / material_color_utilities 0.13.0 / tonalSpot / contrast 0.0\n',
    );
    for (final dark in [false, true]) {
      final name = dark ? 'Dark' : 'Light';
      final factory = dark ? 'darkColorScheme' : 'lightColorScheme';
      kotlin.writeln(
        '\ninternal val flutter${name}SeedSchemes: List<ColorScheme> by lazy { listOf(',
      );
      for (var index = 0; index < nativeSeeds.length; index++) {
        final colors = composeRoles(
          ColorScheme.fromSeed(
            seedColor: Constants.seedColors[index],
            brightness: dark ? Brightness.dark : Brightness.light,
          ),
        );
        expect(colors.length, 36);
        kotlin.writeln(
          '    // Stored theme index $index, seed 0x${hex(Constants.seedColors[index])}.',
        );
        kotlin.writeln('    $factory(');
        for (final role in colors.entries) {
          kotlin.writeln('        ${role.key} = Color(0x${hex(role.value)}),');
          fixture.writeln(
            '$index\t${dark ? "dark" : "light"}\t${role.key}\t${hex(role.value)}',
          );
        }
        kotlin.writeln('    ),');
      }
      kotlin.writeln(') }');
    }
    final outputs = {
      'app/src/main/java/io/github/ktclat/c001apk/nativeapp/settings/FlutterSeedPalettes.kt':
          kotlin.toString(),
      'app/src/test/resources/theme/flutter-seed-palettes.tsv': fixture
          .toString(),
    };
    for (final entry in outputs.entries) {
      final file = File('$nativeRoot/${entry.key}');
      if (Platform.environment['UPDATE_NATIVE_PALETTES'] == '1') {
        file.parent.createSync(recursive: true);
        file.writeAsStringSync(entry.value);
      }
      expect(
        file.readAsStringSync(),
        entry.value,
        reason: 'Generated palette differs: ${entry.key}',
      );
    }
  });
}
